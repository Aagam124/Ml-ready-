"""Generate a runnable Python script and a scikit-learn Pipeline that reproduce a cleaning plan EXACTLY.

The script embeds app/cleaning/runtime.py verbatim (the same code the engine ran), lists every step as
a commented call in canonical order, and fits every learned step (imputers, scalers, encoders, bin edges,
clip bounds) on the TRAINING rows only.
"""
from __future__ import annotations

import pprint
from pathlib import Path
from typing import Any, Dict, List, Optional

from app.cleaning.executor import ordered_enabled, plan_options, split_spec
from app.cleaning.registry import OPS, phase_of

_RUNTIME_PATH = Path(__file__).with_name("runtime.py")
_BEGIN, _END = "# --- MLREADY RUNTIME BEGIN", "# --- MLREADY RUNTIME END"


def runtime_source() -> str:
    text = _RUNTIME_PATH.read_text(encoding="utf-8")
    return text[text.index(_BEGIN): text.index(_END)].rstrip() + "\n"


def _c(text: Any) -> str:
    """Make text safe inside a comment or docstring: one line, printable characters only, no quote/backslash tricks.
    Column names come from user files, so this is a code-injection boundary (see tests)."""
    t = "".join(ch if ch.isprintable() else " " for ch in str(text))
    return t.replace(chr(92), "/").replace(chr(34), chr(39))[:200]


def _lit(value: Any) -> str:
    return pprint.pformat(value, width=100, compact=True, sort_dicts=False)


def _kwargs(params: Dict[str, Any]) -> str:
    return "".join(f", {k}={_lit(v)}" for k, v in params.items())


def _loader(read: Dict[str, Any]) -> str:
    ext = (read.get("ext") or ".csv").lower()
    names = read.get("columns")
    if ext == ".parquet":
        body = "    return pd.read_parquet(path)\n"
    elif ext in (".xlsx", ".xls"):
        body = (f"    df = pd.read_excel(path, sheet_name={_lit(read.get('sheet') or 0)}, header=0)\n"
                f"    df.columns = COLUMNS\n    return df\n")
    else:
        body = (f"    return pd.read_csv(path, sep={_lit(read.get('delimiter') or ',')}, encoding={_lit(read.get('encoding') or 'utf-8-sig')},\n"
                f"                       low_memory=False, skip_blank_lines=True, header=0, names=COLUMNS)\n")
    return f"COLUMNS = {_lit(names)}\n\n\ndef load(path):\n    \"\"\"Read the original file the way MLReady read it (same delimiter, encoding and column names).\"\"\"\n{body}"


def generate_script(steps: List[Dict[str, Any]], target: Optional[str], task_type: Optional[str], read: Dict[str, Any],
                    dataset_name: str = "dataset", seed: int = 42, test_size: float = 0.2) -> str:
    ordered = ordered_enabled(steps)
    spec = split_spec(plan_options(steps), seed, test_size)
    lines: List[str] = []
    w = lines.append
    w("#!/usr/bin/env python3")
    w(f'"""Cleaning script for \'{_c(dataset_name)}\', generated by MLReady.\n')
    w("Usage:  python clean_data.py <original_file> <cleaned_output.csv>\n")
    w("Every step below is listed in the order it runs. Anything the data teaches the step (medians, category lists,")
    w("clip bounds, scaling constants, encodings) is learned from the TRAINING rows only, so no information from the")
    w('test rows leaks into the cleaned data. Re-running this on the original file reproduces the cleaned dataset exactly."""')
    w("import sys\n\nimport numpy as np\nimport pandas as pd\n")
    w("# " + "=" * 92)
    w("# Library code (identical to what MLReady executed). Scroll down to see the plan.")
    w("# " + "=" * 92)
    w(runtime_source())
    w("")
    w("# " + "=" * 92)
    w("# Settings")
    w("# " + "=" * 92)
    w(f"TARGET = {_lit(target)}")
    w(f"TASK_TYPE = {_lit(task_type)}   # binary | multiclass | regression | None")
    w(f"SPLIT = {_lit(spec)}   # train/test split used to decide which rows the steps may learn from\n")
    w(_loader(read))
    w("")
    w("def _split(df):")
    w("    return make_split(df, TARGET, TASK_TYPE, SPLIT['seed'], SPLIT['test_size'], SPLIT['strategy'],")
    w("                      SPLIT['group_column'], SPLIT['time_column'], SPLIT['stratify'])\n")
    w("")
    w("def clean(df):")
    w("    df = df.copy()")
    split_done = False
    n_state = 0
    for i, st in enumerate(ordered, 1):
        meta = OPS[st["op"]]
        if phase_of(st) >= 2 and not split_done:
            w("")
            w("    # ---- Train/test split (after row-level fixes, before columns are dropped) ----")
            w("    is_train = _split(df)")
            w("    train_index = df.index[is_train]")
            split_done = True
        origin = f" [fixes: {_c(st.get('finding_code'))}]" if st.get("finding_code") else ""
        w(f"\n    # Step {i}/{len(ordered)}: {_c(st.get('label') or meta['label'])}{origin}")
        cols = st.get("columns") or []
        if meta["kind"] == "stateless":
            w(f"    df = {meta['impl']}(df, {_lit(cols)}{_kwargs(st.get('params', {}))})")
        else:
            n_state += 1
            var = f"step_{n_state}"
            w(f"    {var} = {meta['impl']}({_lit(cols)}{_kwargs(st.get('params', {}))})")
            w(f"    {var}.fit(df.loc[train_index], target=df[TARGET] if TARGET in df.columns else None)   # learns from TRAIN rows only")
            w(f"    df = {var}.transform(df)")
    w("\n    return df")
    w("")
    w("")
    w("if __name__ == '__main__':")
    w("    if len(sys.argv) != 3:")
    w("        sys.exit(__doc__)")
    w("    cleaned = clean(load(sys.argv[1]))")
    w("    cleaned.to_csv(sys.argv[2], index=False)")
    w("    print(f'Wrote {len(cleaned)} rows x {cleaned.shape[1]} columns to {sys.argv[2]}')")
    return "\n".join(lines) + "\n"


_NATIVE_IMPUTE = {"mean": "mean", "median": "median", "mode": "most_frequent", "constant": "constant"}
_NATIVE_SCALE = {"standard": "StandardScaler()", "minmax": "MinMaxScaler()", "robust": "RobustScaler()"}


def generate_pipeline(steps: List[Dict[str, Any]], target: Optional[str], task_type: Optional[str]) -> str:
    """A module with structural_clean(df) (stateless fixes) and build_preprocessor() -> sklearn Pipeline (learned steps)."""
    ordered = ordered_enabled(steps)
    stateless = [s for s in ordered if OPS[s["op"]]["kind"] == "stateless"]
    stateful = [s for s in ordered if OPS[s["op"]]["kind"] == "stateful"]
    opts = plan_options(steps)
    out: List[str] = []
    w = out.append
    w('"""scikit-learn pipeline for the MLReady cleaning plan.\n')
    w("    df = structural_clean(raw_df)                 # row/column fixes that learn nothing from the data")
    w("    X, y = df.drop(columns=[TARGET]), df[TARGET]")
    w("    X_train, X_test, y_train, y_test = train_test_split(X, y, ...)   # YOUR split (or MLReady's, see clean_data.py)")
    w("    pre = build_preprocessor().fit(X_train, y_train)   # learns medians/categories/scales from TRAIN only")
    w("    X_train_t, X_test_t = pre.transform(X_train), pre.transform(X_test)\n")
    if opts:
        w(f"Modeling settings recommended by MLReady: {_c(opts)}")
    w('Impute and scale steps use native scikit-learn transformers; the rest wrap MLReady\'s runtime classes."""')
    w("import numpy as np\nimport pandas as pd\nfrom sklearn.base import BaseEstimator, TransformerMixin\nfrom sklearn.compose import ColumnTransformer")
    w("from sklearn.impute import SimpleImputer\nfrom sklearn.pipeline import Pipeline\nfrom sklearn.preprocessing import MinMaxScaler, RobustScaler, StandardScaler\n")
    w(runtime_source())
    w(f"\nTARGET = {_lit(target)}\n")
    w("\nclass RuntimeStep(BaseEstimator, TransformerMixin):")
    w('    """Adapter: lets an MLReady runtime class (fit on train, transform any rows) sit inside a Pipeline."""')
    w("    def __init__(self, factory=None):\n        self.factory = factory")
    w("    def fit(self, X, y=None):\n        self.obj_ = self.factory()\n        self.obj_.fit(X, target=None if y is None else pd.Series(np.asarray(y), index=X.index))\n        return self")
    w("    def transform(self, X):\n        return self.obj_.transform(X)")
    w("    def set_output(self, *, transform=None):\n        return self\n")
    w("\ndef structural_clean(df):")
    w('    """Stateless fixes (types, spellings, impossible values, duplicates, dropped columns). Learns nothing."""')
    w("    df = df.copy()")
    for i, st in enumerate(stateless, 1):
        w(f"    # {i}. {_c(st.get('label') or OPS[st['op']]['label'])}")
        w(f"    df = {OPS[st['op']]['impl']}(df, {_lit(st.get('columns') or [])}{_kwargs(st.get('params', {}))})")
    w("    return df\n")
    w("\ndef build_preprocessor():")
    w('    """Learned steps, in order. Call .fit(X_train, y_train) so nothing is learned from test rows."""')
    w("    steps = []")
    for i, st in enumerate(stateful, 1):
        cols, p = st.get("columns") or [], st.get("params", {})
        name = f"{st['op']}_{i}"
        native = None
        if st["op"] == "impute" and p.get("strategy") in _NATIVE_IMPUTE:
            extra = f", fill_value={_lit(p.get('value'))}" if p["strategy"] == "constant" else ""
            native = f"SimpleImputer(strategy={_lit(_NATIVE_IMPUTE[p['strategy']])}{extra})"
        elif st["op"] == "scale" and p.get("method", "standard") in _NATIVE_SCALE:
            native = _NATIVE_SCALE[p.get("method", "standard")]
        if native:
            w(f"    steps.append(({name!r}, ColumnTransformer([('t', {native}, {_lit(cols)})], remainder='passthrough', verbose_feature_names_out=False).set_output(transform='pandas')))")
        else:
            w(f"    steps.append(({name!r}, RuntimeStep(lambda: {OPS[st['op']]['impl']}({_lit(cols)}{_kwargs(p)}))))   # {_c(st.get('label', ''))}")
    w("    return Pipeline(steps)")
    return "\n".join(out) + "\n"
